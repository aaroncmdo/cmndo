  base.nachbesichtigung_termin_datum                  AS nachbesichtigung_termin_datum,
  base.nachbesichtigung_kunde_termin_vorschlaege      AS nachbesichtigung_kunde_termin_vorschlaege,
  base.nachbesichtigung_kunde_termin_eingereicht_am   AS nachbesichtigung_kunde_termin_eingereicht_am,
  base.nachbesichtigung_sv_konfrontation_gewuenscht   AS nachbesichtigung_sv_konfrontation_gewuenscht,
  base.vs_quote_prozent                               AS vs_quote_prozent,
  base.vs_quote_grund                                 AS vs_quote_grund,
  base.vs_quote_akzeptiert_am                         AS vs_quote_akzeptiert_am,
  base.vs_quote_betrag_ausgezahlt                     AS vs_quote_betrag_ausgezahlt,
  base.vs_reaktion_typ                                AS vs_reaktion_typ,
  base.vs_reaktion_am                                 AS vs_reaktion_am,
  base.besichtigungsort_adresse                       AS besichtigungsort_adresse,
  base.abgeschlossen_am                               AS abgeschlossen_am,
  base.kunde_id                                       AS kunde_id,
  base.sv_id                                          AS sv_id,
  base.claim_nummer                                   AS claim_nummer,
  base.main_phase                                     AS main_phase,
  base.sub_phase                                      AS sub_phase
FROM v_claim_base base;
