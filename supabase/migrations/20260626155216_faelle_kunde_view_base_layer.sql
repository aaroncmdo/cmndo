  base.fahrzeug_hersteller_raw                        AS fahrzeug_hersteller,
  base.fahrzeug_modell                                AS fahrzeug_modell,
  base.fahrzeug_baujahr                               AS fahrzeug_baujahr,
  NULL::numeric(10,2)                                 AS auszahlung_kunde_betrag,
  NULL::timestamptz                                   AS auszahlung_kunde_eingegangen_am,
  base.auszahlung_zahlungsweg                         AS auszahlung_zahlungsweg,
  base.eskalation_tag_14_ergebnis                     AS eskalation_tag_14_ergebnis,
  base.eskalation_tag_14_ergebnis_am                  AS eskalation_tag_14_ergebnis_am,
  base.eskalation_tag_21_ergebnis                     AS eskalation_tag_21_ergebnis,
  base.eskalation_tag_21_ergebnis_am                  AS eskalation_tag_21_ergebnis_am,
  base.eskalation_tag_28_ergebnis                     AS eskalation_tag_28_ergebnis,
  base.eskalation_tag_28_ergebnis_am                  AS eskalation_tag_28_ergebnis_am,
